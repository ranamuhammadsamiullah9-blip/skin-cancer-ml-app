import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.model_selection import train_test_split

# 1. Load the dataset
dfp = '/content/HAM10000_metadata.csv'
df = pd.read_csv(dfp)

# 2. Basic EDA
print("Dataset Shape:", df.shape)
print("\nDataset Info:")
print(df.info())
print("\nMissing Values:")
print(df.isnull().sum())

# 3. Class Distribution
print("\nClass Distribution (dx):")
print(df['dx'].value_counts(normalize=True) * 100)

# 4. Stratified Split to maintain class proportions
train_df, test_df = train_test_split(
    df,
    test_size=0.2,
    random_state=42,
    stratify=df['dx']
)

print(f"\nTrain set shape: {train_df.shape}")
print(f"Test set shape: {test_df.shape}")

# 5. Compare Distributions
fig, axes = plt.subplots(1, 2, figsize=(14, 5), sharey=True)
sns.countplot(data=train_df, x='dx', ax=axes[0], order=df['dx'].value_counts().index)
axes[0].set_title('Train Set - Class Distribution')
axes[0].tick_params(axis='x', rotation=45)

sns.countplot(data=test_df, x='dx', ax=axes[1], order=df['dx'].value_counts().index)
axes[1].set_title('Test Set - Class Distribution')
axes[1].tick_params(axis='x', rotation=45)

plt.tight_layout()
plt.show()

import tensorflow as tf
from tensorflow.keras import layers, models
from sklearn.preprocessing import LabelEncoder

# Encode target labels (dx)
label_encoder = LabelEncoder()
train_labels = label_encoder.fit_transform(train_df['dx'])
test_labels = label_encoder.transform(test_df['dx'])

num_classes = len(label_encoder.classes_)
print(f"Number of classes: {num_classes} ({label_encoder.classes_})")

# For demonstration, we'll design a CNN model topology.
# In a practical scenario with actual image files, you would load and preprocess images via image paths.
model = models.Sequential([
    # Assuming input images of size 128x128 with 3 channels (RGB)
    layers.Input(shape=(128, 128, 3)),
    layers.Conv2D(32, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(64, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Conv2D(128, (3, 3), activation='relu'),
    layers.MaxPooling2D((2, 2)),
    layers.Flatten(),
    layers.Dense(128, activation='relu'),
    layers.Dropout(0.5),
    layers.Dense(num_classes, activation='softmax')
])

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

model.summary()

# Save the compiled Keras model
model.save('ham10000_cnn_model.keras')
print("Model saved successfully as 'ham10000_cnn_model.keras'!")